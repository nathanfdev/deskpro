    /*
      * Get an array of objects with title/value properties for each tz.
      *
      * @return {Array}
    */
    getOptions() {
      const ret = [];
      return (() => {
        const result = [];
        for (let tz of Array.from(TzData.tzData)) {
          var title;
          if (tz.title === 'UTC') {
            title = 'UTC';
          } else {
            title = `${tz.parent_title} / ${tz.title}`;
          }

          result.push(ret.push({
            title,
            value: id
          }));
        }
        return result;
      })();
    }


    /*
      * Get an array of grouped tz values
      *
      * @return {Array}
    */
    getGroupedOptions() {
      const ret = [];
      const group_map = {};

      for (let tz of Array.from(TzData.tzData)) {
        var parent_obj, parent_title;
        if (tz.title === 'UTC') {
          parent_title = 'Other';
        } else {
          ({ parent_title } = tz);
        }

        if (!group_map[parent_title]) {
          parent_obj = {
            title: parent_title,
            options: []
          };
          ret.push(parent_obj);
          group_map[parent_title] = parent_obj;
        } else {
          parent_obj = group_map[parent_title];
        }

        parent_obj.options.push({
          title: tz.title,
          value: tz.id
        });
      }

      return ret;
    }

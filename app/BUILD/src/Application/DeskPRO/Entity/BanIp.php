namespace Application\DeskPRO\Entity;

use Application\DeskPRO\Domain\DomainObject;
use Doctrine\ORM\Mapping\ClassMetadata;
use Doctrine\ORM\Mapping\ClassMetadataInfo;

/**
 * Ban an IP addresses and ranges.
 *
 * @property string  $banned_ip
 * @property bool $is_range
 */
class BanIp extends DomainObject
{
    /**
     * Autogenerated id.
     *
     * @var int
     */
    protected $id;

    /**
     * The banned IP address (human readable).
     *
     * @var string
     */
    protected $banned_ip;

    /**
     * Mark as range.
     *
     * @var int
     */
    protected $is_range = false;

    /**
     * End of the IP range.
     *
     * @var int
     */
    protected $ip_end;

    public function getId()
    {
        return $this->id;
    }

    /**
     * @return BanIp
     */
    public static function createBanIp()
    {
        return new self();
    }

    public function setBannedIp($ip)
    {
        // we already have a mask
        if (strpos($ip, '/') !== false) {
            list($ip, $blocks) = explode('/', $ip, 2);
            $this->setModelField('is_range', true);
            $defaultBlocks = filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV6) ? 128 : 32;
        } else {
            $blocks = $defaultBlocks = filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV6) ? 128 : 32;
        }

        if (!filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV6)) {
            // checking 192.168.*.* format
            $ip    = str_replace('.*', '', $ip);
            $count = 0;
            $ip    = explode('.', $ip);
            for ($i = count($ip); $i < 4; ++$i) {
                $ip[] = 0;
                ++$count;
            }
            $ip = implode('.', $ip);

            if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) && $count > 0) {
                $this->setModelField('is_range', true);
                $blocks -= ($count * 8);
            }
        }

        $humanReadable = $ip.(($blocks && $blocks != $defaultBlocks) ? "/$blocks" : '');

        $this->setModelField('banned_ip', $humanReadable);
    }

    ############################################################################
    # Doctrine Metadata
    ############################################################################

    public static function loadMetadata(ClassMetadata $metadata)
    {
        $metadata->setInheritanceType(ClassMetadataInfo::INHERITANCE_TYPE_NONE);
        $metadata->customRepositoryClassName = 'Application\DeskPRO\EntityRepository\BanIp';
        $metadata->setPrimaryTable(
            [
                'name'    => 'ban_ips',
                'indexes' => [
                    'is_range_idx' => ['columns' => ['is_range']],
                ],
            ]
        );
        $metadata->setChangeTrackingPolicy(ClassMetadataInfo::CHANGETRACKING_NOTIFY);
        $metadata->setIdGeneratorType(ClassMetadataInfo::GENERATOR_TYPE_IDENTITY);

        $metadata->mapField(
            [
                'fieldName'  => 'id',
                'type'       => 'integer',
                'precision'  => 0,
                'scale'      => 0,
                'nullable'   => false,
                'columnName' => 'id',
                'id'         => true,
            ]
        );

        $metadata->mapField(
            [
                'fieldName'  => 'banned_ip',
                'type'       => 'string',
                'length'     => 100,
                'precision'  => 0,
                'scale'      => 0,
                'nullable'   => false,
                'columnName' => 'banned_ip',
            ]
        );

        $metadata->mapField(
            [
                'fieldName'  => 'is_range',
                'type'       => 'boolean',
                'precision'  => 0,
                'scale'      => 0,
                'nullable'   => false,
                'columnName' => 'is_range',
            ]
        );
    }
}

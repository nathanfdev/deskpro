<?php

namespace Application\DeskPRO\Proxy;

use Application\DeskPRO\Proxy\Exception\FailedToExchangeRequestTokenException;
use Application\DeskPRO\Proxy\Exception\FailedToResignS3UrlException;
use DeskPRO\Bundle\AppBundle\AppSecret\AppSecret;
use DeskPRO\Bundle\AppBundle\Util\HttpClient;
use Firebase\JWT\JWT;

/**
 * Class OutboundHttpProxy
 *
 * @package Application\DeskPRO\Proxy
 */
class OutboundHttpProxy
{
    /**
     * Local var cache of token TTL in seconds
     */
    const TOKEN_CACHE_TTL = 10;

    /**
     * @var AppSecret
     */
    private $appSecret;

    /**
     * @var array
     */
    private $cache = [];

    /**
     * Constructor.
     *
     * @param AppSecret $appSecret
     */
    public function __construct(AppSecret $appSecret)
    {
        $this->appSecret = $appSecret;
    }

    /**
     * Get a service token for Pusher
     *
     * @param string $siteId
     * @param string $appId
     * @param string $authKey
     * @return string
     * @throws FailedToExchangeRequestTokenException
     */
    public function getPusherServiceToken($siteId, $appId, $authKey, $channelPrefix)
    {
        return $this->fetchServiceToken($siteId, 'pusher', [
            'appId'   => (string) $appId,
            'authKey' => (string) $authKey,
            'channelPrefix' => (string) $channelPrefix,
        ]);
    }

    /**
     * Get a service token for Elasticsearch
     *
     * @param string $siteId
     * @param string $path
     * @return string
     * @throws FailedToExchangeRequestTokenException
     */
    public function getElasticsearchServiceToken($siteId, $proto, $path, $port, $method)
    {
        return $this->fetchServiceToken($siteId, 'elasticsearch', [
            'proto'  => (string) $proto,
            'path'   => (string) $path,
            'port'   => (string) $port,
            'method' => (string) $method,
        ]);
    }

    /**
     * Get a service token for AWS S3
     *
     * @param string $siteId
     * @return mixed|string|null
     * @throws FailedToExchangeRequestTokenException
     */
    public function getS3ServiceToken($siteId, $region, $bucket, $key, $method, $acl = null)
    {
        return $this->fetchServiceToken($siteId, 's3', [
            's3Region' => (string) $region,
            's3Bucket' => (string) $bucket,
            's3Key'    => (string) $key,
            's3Method' => (string) $method,
            's3Acl'    => $acl === null ? null : (string) $acl,
        ]);
    }

    /**
     * Request a re-signed URL from the S3 resigning endpoint
     *
     * @param string $serviceToken JWT generated by @see getS3ServiceToken
     * @return mixed
     * @throws FailedToResignS3UrlException
     */
    public function getPreSignedS3Url($serviceToken)
    {
        global $DP_ENV;

        $proxyUrl = $DP_ENV->getConfig('env.http_proxy_url');

        $client = new HttpClient([
            'base_uri' => $proxyUrl,
        ]);

        try {
            $response = $this->retry(function () use ($client, $serviceToken) {
                return $client->get('/s3/signed-url', [
                    'headers' => [
                        'Accept'              => 'application/json',
                        'Cache-Control'       => 'no-cache',
                        'Content-Type'        => 'application/json',
                        'Proxy-Authorization' => 'Bearer '.$serviceToken,
                    ],
                ]);
            });

            $response = json_decode((string) $response->getBody());

            return $response->url;
        } catch (\Exception $e) {
            throw new FailedToResignS3UrlException('Failed to get re-signed S3 URL', 0, $e);
        }
    }

    /**
     * Exchanges a "request" token (generated here) for a "service" token used by
     * our outbound proxy services
     *
     * @param string $siteId
     * @param string $service
     * @param array $payload
     * @throws FailedToExchangeRequestTokenException
     */
    protected function fetchServiceToken($siteId, $service, $payload = [])
    {
        global $DP_ENV;

        $tokenKey = md5($siteId.$service.\json_encode($payload));

        if ($cachedToken = $this->cacheGet($tokenKey)) {
            return $cachedToken;
        }

        $tokenExchangeUrl = $DP_ENV->getConfig('env.proxy_token_exchange_url');

        if (empty($tokenExchangeUrl)) {
            throw new FailedToExchangeRequestTokenException(
                'Token exchange URL is not set, in production this should be set via the env var DP_PROXY_TOKEN_EXCHANGE_URL'
            );
        }

        if (empty($siteId)) {
            throw new FailedToExchangeRequestTokenException('Site ID not provided when exchanging request token');
        }

        $payload = array_merge($payload, [
            'sub' => (string) $siteId,
            'srv' => $service,
        ]);

        $requestToken = JWT::encode($payload, $this->appSecret->getAppSecret());

        $client = new HttpClient([
            'base_uri' => $tokenExchangeUrl,
        ]);

        try {
            $response = $this->retry(function () use ($client, $requestToken) {
                return $client->post('/exchange', [
                    'headers' => [
                        'Accept'        => 'application/jwt',
                        'Cache-Control' => 'no-cache',
                        'Content-Type'  => 'application/json',
                        'Authorization' => 'Bearer '.$requestToken,
                    ],
                ]);
            });
        } catch (\Exception $e) {
            throw new FailedToExchangeRequestTokenException('Failed to get service token from token exchange', 0, $e);
        }

        if ($response->getStatusCode() !== 200) {
            throw new FailedToExchangeRequestTokenException(sprintf(
                'Request to get service token returned unsuccessful response, [%d] status code returned',
                $response->getStatusCode()
            ));
        }

        $token = (string) $response->getBody();

        $this->cacheStore($tokenKey, $token);

        return $token;
    }

    /**
     * @return bool
     */
    public static function isUsingProxy()
    {
        return (defined('DPC_IS_CLOUD') && defined('DPC_IS_USING_OUTBOUND_PROXY'));
    }

    /**
     * Retry with exponential back-off
     *
     * @param callable $try
     * @param int $maxRetries
     * @param float $exponent
     * @param int $wait
     * @return mixed
     * @throws \Exception
     */
    private function retry(callable $try, $maxRetries = 5, $exponent = 1.5, $wait = 1)
    {
        try {
            return $try();
        } catch (\Exception $e) {
            if ($maxRetries > 0) {
                sleep($wait);
                return $this->retry($try, $maxRetries - 1, $exponent, $wait * $exponent);
            }

            throw $e;
        }
    }

    /**
     * @param string $key
     * @param mixed $value
     */
    private function cacheStore($key, $value)
    {
        $this->cache[$key] = [
            $value,
            time() + self::TOKEN_CACHE_TTL
        ];
    }

    /**
     * @param $key
     * @return mixed|null
     */
    private function cacheGet($key)
    {
        $unexpiredValues = array_filter($this->cache, function ($v) {
            return time() <= $v[1];
        });

        return isset($unexpiredValues[$key])
            ? $unexpiredValues[$key][0]
            : null
        ;
    }
}

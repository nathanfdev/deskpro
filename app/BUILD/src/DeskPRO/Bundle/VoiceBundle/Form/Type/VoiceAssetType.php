<?php

namespace DeskPRO\Bundle\VoiceBundle\Form\Type;

use DeskPRO\Bundle\AppBundle\Entity\VoiceAsset\AbstractVoiceAsset;
use DeskPRO\Bundle\AppBundle\Entity\VoiceAsset\AbstractVoiceBlobAsset;
use DeskPRO\Bundle\AppBundle\Form\Type\BlobAuthType;
use Symfony\Component\Form\AbstractType;
use Symfony\Component\Form\Extension\Core\Type\ChoiceType;
use Symfony\Component\Form\Extension\Core\Type\TextType;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\Form\FormEvent;
use Symfony\Component\Form\FormEvents;

/**
 * Class VoiceAssetType.
 */
class VoiceAssetType extends AbstractType
{
    /**
     * {@inheritdoc}
     */
    public function buildForm(FormBuilderInterface $builder, array $options)
    {
        $builder
            ->add('type', ChoiceType::class, [
                'mapped'            => false,
                'choices_as_values' => true,
                'choices'           => [
                    AbstractVoiceAsset::TYPE_TEXT,
                    AbstractVoiceAsset::TYPE_UPLOAD,
                    AbstractVoiceAsset::TYPE_RECORD,
                ],
            ])
        ;

        $builder->addEventListener(FormEvents::PRE_SUBMIT, [$this, 'onPreSubmit']);
        $builder->addEventListener(FormEvents::SUBMIT, [$this, 'onSubmit']);
        $builder->addEventListener(FormEvents::POST_SUBMIT, [$this, 'onPostSubmit']);
    }

    /**
     * @internal
     *
     * @param FormEvent $event
     */
    public function onPreSubmit(FormEvent $event)
    {
        $data  = $event->getData();
        $form  = $event->getForm();
        $asset = $form->getData();

        // create entity instance by type
        if (empty($data['type'])) {
            $asset = null;
        } else {
            if (!$asset instanceof AbstractVoiceAsset || $asset->getType() !== $data['type']) {
                $asset = AbstractVoiceAsset::createByType($data['type']);
            }
        }

        $form->setData($asset);

        // force fields submission
        if (is_array($data)) {
            if (!isset($data['type'])) {
                $data['type'] = '';
            }

            if ($data['type'] === AbstractVoiceAsset::TYPE_TEXT) {
                if (!isset($data['language'])) {
                    $data['language'] = '';
                }
                if (!isset($data['text'])) {
                    $data['text'] = '';
                }
            } elseif (in_array($data['type'], [AbstractVoiceAsset::TYPE_UPLOAD, AbstractVoiceAsset::TYPE_RECORD])) {
                if (!isset($data['blob'])) {
                    $data['blob'] = '';
                }

                if ($data['type'] === AbstractVoiceAsset::TYPE_RECORD) {
                    if (!isset($data['name'])) {
                        $data['name'] = '';
                    }
                }
            }
        }

        // add form fields
        $type = isset($data['type']) ? $data['type'] : null;

        if ($type === AbstractVoiceAsset::TYPE_TEXT) {
            $form
                ->add('text', TextType::class, [
                    'property_path' => 'text',
                ])
                ->add('language', TextType::class, [
                    'property_path' => 'language',
                ])
                ->add('auto_generated', TextType::class, [
                    'property_path' => 'autoGenerated',
                ])
            ;
        } elseif (in_array($type, [AbstractVoiceAsset::TYPE_UPLOAD, AbstractVoiceAsset::TYPE_RECORD])) {
            $form->add('blob', BlobAuthType::class, [
                'property_path' => 'blob',
            ]);

            if ($type === AbstractVoiceAsset::TYPE_RECORD) {
                $form->add('name', TextType::class, [
                    'property_path' => 'name',
                ]);
            }
        }

        $event->setData($data);
    }

    /**
     * @internal
     *
     * @param FormEvent $event
     */
    public function onSubmit(FormEvent $event)
    {
        $data = $event->getData();
        if (!$data instanceof AbstractVoiceAsset) {
            $event->setData(null);
        }
    }

    /**
     * @internal
     *
     * @param FormEvent $event
     */
    public function onPostSubmit(FormEvent $event)
    {
        $data = $event->getData();
        if ($data instanceof AbstractVoiceBlobAsset && $data->getBlob()) {
            $data->getBlob()->setIsTemp(false);
        }
    }
}

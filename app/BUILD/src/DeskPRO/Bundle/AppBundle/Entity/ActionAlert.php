namespace DeskPRO\Bundle\AppBundle\Entity;

use Doctrine\Common\NotifyPropertyChanged;
use Doctrine\ORM\Mapping as ORM;
use JMS\Serializer\Annotation as JMS;
use Symfony\Component\Validator\Constraints as Assert;

/**
 * Class Event.
 *
 * @ORM\Entity
 * @ORM\Table(name="notify_action_alerts")
 * @ORM\ChangeTrackingPolicy("DEFERRED_IMPLICIT")
 * @ORM\InheritanceType("NONE")
 *
 * @JMS\ExclusionPolicy("all")
 *
 * @category Entities
 */
class ActionAlert implements EntityInterface, NotifyPropertyChanged, NotificationEntityInterface
{
    use NotifyPropertyChangedTrait;

    /**
     * The unique ID (autogenerated by db).
     *
     * @ORM\Id()
     * @ORM\Column(type="integer")
     * @ORM\GeneratedValue(strategy="IDENTITY")
     *
     * @JMS\Expose()
     * @JMS\Type("integer")
     *
     * @var int
     */
    protected $id;

    /**
     * Target indetity (means user id).
     *
     * @ORM\Column(type="integer")
     * @Assert\NotNull()
     *
     * @JMS\Expose()
     * @JMS\Type("integer")
     *
     * @var int
     */
    protected $target_id;

    /**
     * String identity.
     *
     * @ORM\Column(type="string", length=80)
     * @Assert\NotNull()
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @var string
     */
    protected $uuid;

    /**
     * DateTime when alert was created.
     *
     * @ORM\Column(type="datetime", nullable=false)
     * @Assert\NotNull()
     *
     * @JMS\Expose()
     * @JMS\Type("DateTime")
     *
     * @var \DateTime
     */
    protected $date_created;

    /**
     * Relative to array data.
     *
     * @ORM\Column(type="json_array", nullable=false)
     * @Assert\NotNull()
     *
     * @JMS\Expose()
     * @JMS\Type("array")
     *
     * @var array
     */
    protected $data;

    /**
     * Alert type.
     *
     * @ORM\Column(type="string", length=100)
     * @Assert\NotNull()
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @var string
     */
    protected $type;

    /**
     * @return int
     */
    public function getId()
    {
        return $this->id;
    }

    /**
     * @param int $id
     *
     * @return Event
     */
    public function setId($id)
    {
        $this->id = $id;

        return $this;
    }

    /**
     * @return mixed
     */
    public function getTargetId()
    {
        return $this->target_id;
    }

    /**
     * @param mixed $target_id
     *
     * @return ActionAlert
     */
    public function setTargetId($target_id)
    {
        $this->target_id = $target_id;

        return $this;
    }

    /**
     * @return string
     */
    public function getUuid()
    {
        return $this->uuid;
    }

    /**
     * @param string $uuid
     *
     * @return ActionAlert
     */
    public function setUuid($uuid)
    {
        $this->uuid = $uuid;

        return $this;
    }

    /**
     * @return \DateTime
     */
    public function getDateCreated()
    {
        return $this->date_created;
    }

    /**
     * Timestamp representation of date_created.
     *
     * @JMS\VirtualProperty()
     * @JMS\Type("integer")
     * @JMS\SerializedName("timestamp")
     *
     * @return int
     */
    public function getTimestamp()
    {
        return $this->date_created->getTimestamp();
    }

    /**
     * @param \DateTime $date_created
     *
     * @return ActionAlert
     */
    public function setDateCreated($date_created)
    {
        $this->date_created = $date_created;

        return $this;
    }

    /**
     * @return array
     */
    public function getData()
    {
        return $this->data;
    }

    /**
     * @param array $data
     *
     * @return ActionAlert
     */
    public function setData($data)
    {
        $this->data = $data;

        return $this;
    }

    /**
     * @return string
     */
    public function getType()
    {
        return $this->type;
    }

    /**
     * @param string $type
     *
     * @return ActionAlert
     */
    public function setType($type)
    {
        $this->type = $type;
    }
}

<?php

namespace DeskPRO\Bundle\AppBundle\Entity\VoiceAsset;

use Doctrine\ORM\Mapping as ORM;
use JMS\Serializer\Annotation as JMS;
use Symfony\Component\Validator\Constraints as Assert;

/**
 * Class VoiceTextAsset.
 *
 * @JMS\ExclusionPolicy("all")
 * @ORM\Entity
 */
class VoiceTextAsset extends AbstractVoiceAsset
{
    /**
     * @ORM\Column(name="text", type="text")
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @Assert\NotBlank()
     *
     * @var string
     */
    protected $text = '';

    /**
     * @ORM\Column(name="language", type="text")
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @Assert\NotBlank()
     * @Assert\Choice(choices={
     *     "da-DK",
     *     "de-DE",
     *     "en-AU",
     *     "en-CA",
     *     "en-GB",
     *     "en-IN",
     *     "en-US",
     *     "ca-ES",
     *     "es-ES",
     *     "es-MX",
     *     "fi-FI",
     *     "fr-CA",
     *     "fr-FR",
     *     "it-IT",
     *     "ja-JP",
     *     "ko-KR",
     *     "nb-NO",
     *     "nl-NL",
     *     "pl-PL",
     *     "pt-BR",
     *     "pt-PT",
     *     "ru-RU",
     *     "sv-SE",
     *     "zh-CN",
     *     "zh-HK",
     *     "zh-TW"
     * })
     *
     * @var string
     */
    protected $language = '';

    /**
     * @ORM\Column(name="auto_generated", type="boolean")
     *
     * @JMS\Expose()
     * @JMS\Type("boolean")
     *
     * @var bool
     */
    protected $autoGenerated = false;

    /**
     * {@inheritdoc}
     */
    public function getType()
    {
        return AbstractVoiceAsset::TYPE_TEXT;
    }

    /**
     * @return string
     */
    public function getText()
    {
        return $this->text;
    }

    /**
     * @param string $text
     *
     * @return $this
     */
    public function setText($text)
    {
        $this->setModelField('text', $text);

        return $this;
    }

    /**
     * @return string
     */
    public function getLanguage()
    {
        return $this->language;
    }

    /**
     * @param string $language
     *
     * @return $this
     */
    public function setLanguage($language)
    {
        $this->setModelField('language', $language);

        return $this;
    }

    /**
     * @return bool
     */
    public function getAutoGenerated()
    {
        return $this->autoGenerated;
    }

    /**
     * @param bool $autoGenerated
     *
     * @return $this
     */
    public function setAutoGenerated($autoGenerated)
    {
        $this->setModelField('autoGenerated', $autoGenerated);

        return $this;
    }
}

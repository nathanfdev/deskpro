<?php

namespace DeskPRO\Bundle\AppBundle\Entity;

use Application\DeskPRO\Entity\Person;
use DeskPRO\Component\Util\MapUtils;
use Doctrine\Common\NotifyPropertyChanged;
use Doctrine\ORM\Mapping as ORM;
use JMS\Serializer\Annotation as JMS;
use Orb\Util\NullValue;
use Symfony\Component\Validator\Constraints as Assert;
use Zend\Db\TableGateway\Exception\RuntimeException;

/**
 * @ORM\Entity()
 * @ORM\Table(name="client_devices", uniqueConstraints={@ORM\UniqueConstraint(name="device",columns={"device_id", "person_id", "app_type"})})
 * @ORM\ChangeTrackingPolicy("NOTIFY")
 * @ORM\InheritanceType("NONE")
 * @JMS\ExclusionPolicy("all")
 */
class ClientDevice implements EntityInterface, NotifyPropertyChanged
{
    use NotifyPropertyChangedTrait;

    const TYPE_GENERIC        = 'generic';
    const TYPE_IOS_GENERIC    = 'ios';
    const TYPE_IOS_IPHONE     = 'ios.iphone';
    const TYPE_IOS_IPAD       = 'ios.ipad';
    const TYPE_ANDROID        = 'android';
    const TYPE_ANDROID_PHONE  = 'android.phone';
    const TYPE_ANDROID_TABLET = 'android.tablet';

    const APP_TYPE_MOBILE = 'mobile';

    const DAT_NOTIFY_TOKEN = 'notify.token';

    /**
     * @var int
     * @ORM\Id()
     * @ORM\Column(type="integer")
     * @ORM\GeneratedValue(strategy="IDENTITY")
     */
    protected $id;

    /**
     * @ORM\ManyToOne(targetEntity="Application\DeskPRO\Entity\Person")
     * @ORM\JoinColumn(name="person_id", referencedColumnName="id", onDelete="CASCADE")
     *
     * @Assert\NotNull()
     *
     * @JMS\Expose()
     * @JMS\Type("entity<Application\DeskPRO\Entity\Person>")
     *
     * @var Person
     */
    protected $person;

    /**
     * The device ID should be a unique ID in the system. It can be any string
     * and may only have meaning within the DeskPRO system as a way to identigy the
     * device within a particular application.
     *
     * Typically this is a real device ID, or at least a device ID generated by
     * the particular application on the device.
     *
     * @var string
     * @ORM\Column(type="string", length=255)
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @Assert\NotNull()
     */
    protected $device_id;

    /**
     * The type of device.
     *
     * @var string
     * @ORM\Column(type="string", length=80)
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @Assert\NotNull()
     */
    protected $device_type = self::TYPE_GENERIC;

    /**
     * This is the full device type. E.g. it might be complicated or less
     * readable than the device_type because it might include model numbers
     * or other manufacturer info.
     *
     * @var string
     * @ORM\Column(type="string", length=80)
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @Assert\NotNull()
     */
    protected $device_agent = '';

    /**
     * A human name for the device. E.g. "Christopher's iPhone".
     *
     * @var string
     * @ORM\Column(type="string", length=255)
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @Assert\NotNull()
     */
    protected $device_name = '';

    /**
     * The type of app this device was registered with.
     *
     * @var string
     * @ORM\Column(type="string", length=80)
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @Assert\NotNull()
     */
    protected $app_type = self::APP_TYPE_MOBILE;

    /**
     * If the device is capable of being a target for notifications.
     *
     * @var bool
     * @ORM\Column(type="boolean", nullable=false)
     *
     * @JMS\Expose()
     * @JMS\Type("boolean")
     *
     * @Assert\NotNull()
     */
    protected $can_notify = false;

    /**
     * Any data we have about this device.
     *
     * @ORM\Column(type="json_array", nullable=false)
     *
     * @Assert\NotNull()
     *
     * @var array
     */
    protected $data = [];

    /**
     * When the device was registered.
     *
     * @var \DateTime
     * @ORM\Column(type="datetime", nullable=false)
     *
     * @JMS\Expose()
     * @JMS\Type("DateTime")
     *
     * @Assert\NotNull()
     */
    protected $date_created;

    public function __construct()
    {
        $this->setModelField('date_created', new \DateTime());
    }

    /**
     * @return int
     */
    public function getId()
    {
        return $this->id;
    }

    /**
     * @return string
     */
    public function getDeviceId()
    {
        return $this->device_id;
    }

    /**
     * @param string $device_id
     *
     * @return $this
     */
    public function setDeviceId($device_id)
    {
        $this->setModelField('device_id', $device_id);

        return $this;
    }

    /**
     * @return Person
     */
    public function getPerson()
    {
        return $this->person;
    }

    /**
     * @param Person $person
     *
     * @return $this
     */
    public function setPerson($person)
    {
        $this->setModelField('person', $person);

        return $this;
    }

    /**
     * @return string
     */
    public function getDeviceType()
    {
        return $this->device_type;
    }

    /**
     * @param string $device_type
     *
     * @return $this
     */
    public function setDeviceType($device_type)
    {
        $this->setModelField('device_type', $device_type);

        return $this;
    }

    /**
     * @return string
     */
    public function getDeviceAgent()
    {
        return $this->device_agent;
    }

    /**
     * @param string $device_agent
     *
     * @return $this
     */
    public function setDeviceAgent($device_agent)
    {
        $this->setModelField('device_agent', $device_agent ?: '');

        return $this;
    }

    /**
     * @return string
     */
    public function getDeviceName()
    {
        return $this->device_name;
    }

    /**
     * @param string $device_name
     *
     * @return $this
     */
    public function setDeviceName($device_name)
    {
        $this->setModelField('device_name', $device_name ?: '');

        return $this;
    }

    /**
     * @return mixed
     */
    public function getAppType()
    {
        return $this->app_type;
    }

    /**
     * @param mixed $app_type
     *
     * @return $this
     */
    public function setAppType($app_type)
    {
        $this->setModelField('app_type', $app_type);

        return $this;
    }

    /**
     * @return bool
     */
    public function canNotify()
    {
        return $this->can_notify;
    }

    /**
     * @param string $token
     *
     * @return $this
     */
    public function enableNotifications($token)
    {
        $this->setModelField('can_notify', true);
        $this->setData(self::DAT_NOTIFY_TOKEN, $token);

        return $this;
    }

    /**
     * @return $this
     */
    public function disableNotifications()
    {
        $this->setModelField('can_notify', false);
        $this->setData(self::DAT_NOTIFY_TOKEN, null);

        return $this;
    }

    /**
     * @return string
     */
    public function getNotifyToken()
    {
        if (!$this->canNotify()) {
            throw new RuntimeException('The device does not support notifications');
        }

        return $this->getData(self::DAT_NOTIFY_TOKEN);
    }

    /**
     * @internal
     *
     * @JMS\VirtualProperty()
     * @JMS\SerializedName("notify_token")
     * @JMS\Type("string")
     *
     * @return string|null
     */
    public function getNotifyTokenForApi()
    {
        return $this->canNotify() ? $this->getNotifyToken() : null;
    }

    /**
     * @param string $path
     * @param mixed  $default
     *
     * @return mixed
     */
    public function getData($path, $default = null)
    {
        return MapUtils::getIn($this->data, $path, $default);
    }

    /**
     * @param string $path
     *
     * @return bool
     */
    public function hasData($path)
    {
        return MapUtils::getIn($this->data, $path, NullValue::get()) !== NullValue::get();
    }

    /**
     * @param string $path
     * @param mixed  $v
     *
     * @return $this
     */
    public function setData($path, $v)
    {
        $data = MapUtils::setIn($this->data, $path, $v);
        $this->setModelField('data', $data);

        return $this;
    }

    /**
     * @return array
     */
    public function getAllData()
    {
        return $this->data;
    }

    /**
     * @param array $data
     *
     * @return $this
     */
    public function setAllData(array $data)
    {
        $this->setModelField('data', $data);

        return $this;
    }

    /**
     * @return \DateTime
     */
    public function getDateCreated()
    {
        return $this->date_created;
    }
}

<?php

namespace DeskPRO\Bundle\AppBundle\Entity\Report;

use Application\Deskpro\Entity\Person;
use Application\DeskPRO\Entity\ReportDashboardReport;
use DeskPRO\Bundle\AppBundle\Entity\EntityInterface;
use DeskPRO\Bundle\AppBundle\Entity\NotifyPropertyChangedTrait;
use Doctrine\Common\NotifyPropertyChanged;
use Doctrine\ORM\Mapping as ORM;
use JMS\Serializer\Annotation as JMS;
use Symfony\Component\Validator\Constraints as Assert;

/**
 * Class Event.
 *
 * @ORM\Entity
 * @ORM\Table(name="scheduled_reports")
 * @ORM\ChangeTrackingPolicy("NOTIFY")
 * @ORM\InheritanceType("NONE")
 *
 * @JMS\ExclusionPolicy("all")
 *
 * @category Entities
 */
class ScheduledReport implements EntityInterface, NotifyPropertyChanged
{
    use NotifyPropertyChangedTrait;

    const FREQUENCY_DAILY     = 'daily';
    const FREQUENCY_WEEKLY    = 'weekly';
    const FREQUENCY_MONTHLY   = 'monthly';
    const FREQUENCY_BIMONTHLY = 'bimonthly';

    /**
     * The unique ID (autogenerated by db).
     *
     * @ORM\Id()
     * @ORM\Column(type="bigint")
     * @ORM\GeneratedValue(strategy="IDENTITY")
     *
     * @var int
     */
    protected $id;

    /**
     * Person scheduled this report (means user id).
     *
     * @ORM\ManyToOne(targetEntity="Application\DeskPRO\Entity\Person")
     * @ORM\JoinColumn(name="person_id", referencedColumnName="id", onDelete="CASCADE")
     *
     * @var Person
     */
    protected $person;

    /**
     * @ORM\ManyToOne(targetEntity="Application\DeskPRO\Entity\ReportDashboardReport")
     * @ORM\JoinColumn(name="report_id", referencedColumnName="id", onDelete="CASCADE")
     *
     * @var ReportDashboardReport
     */
    protected $report;

    /**
     * @ORM\Column(type="json_array", name="when_setting")
     * It is called whenSetting becasue Doctrine not trying to avoid using reserved keywords like 'when'
     *
     * @JMS\Expose()
     * @JMS\Type("array")
     * @JMS\SerializedName("when")
     *
     * @var array
     */
    protected $whenSetting;

    /**
     * @ORM\Column(type="string", length=32, name="when_tz")
     *
     * @var string
     */
    protected $whenTz;

    /**
     * @ORM\Column(type="string", length=64)
     *
     * @JMS\Expose()
     * @JMS\Type("string")
     *
     * @var string
     */
    protected $frequency;

    /**
     * @ORM\Column(name="next_send_date", type="datetime", nullable=true)
     *
     * @var \DateTime
     */
    protected $nextSendDate;

    /**
     * @ORM\Column(name="send_to", type="json_array", nullable=true)
     *
     * @JMS\Expose()
     * @JMS\Type("array")
     *
     * @Assert\All(constraints={
     *   @Assert\Email(strict="true")
     * })
     *
     * @var array
     */
    protected $sendTo;

    /**
     * @return int
     */
    public function getId()
    {
        return $this->id;
    }

    /**
     * @return Person
     */
    public function getPerson()
    {
        return $this->person;
    }

    /**
     * @param Person $person
     *
     * @return $this
     */
    public function setPerson(Person $person)
    {
        $this->setModelField('person', $person);

        return $this;
    }

    /**
     * @return ReportDashboardReport
     */
    public function getReport()
    {
        return $this->report;
    }

    /**
     * @param ReportDashboardReport $report
     *
     * @return $this
     */
    public function setReport($report)
    {
        $this->setModelField('report', $report);

        return $this;
    }

    /**
     * @return array
     */
    public function getWhenSetting()
    {
        return $this->whenSetting;
    }

    /**
     * @param array $whenSetting
     *
     * @return $this
     */
    public function setWhenSetting(array $whenSetting)
    {
        $this->setModelField('whenSetting', $whenSetting);

        return $this;
    }

    /**
     * @return string
     */
    public function getWhenTz()
    {
        return $this->whenTz;
    }

    /**
     * @param string $whenTz
     *
     * @return $this
     */
    public function setWhenTz($whenTz)
    {
        $this->setModelField('whenTz', $whenTz);

        return $this;
    }

    /**
     * @return string
     */
    public function getFrequency()
    {
        return $this->frequency;
    }

    /**
     * @param string $frequency
     *
     * @return $this
     */
    public function setFrequency($frequency)
    {
        $this->setModelField('frequency', $frequency);

        return $this;
    }

    /**
     * @return \DateTime
     */
    public function getNextSendDate()
    {
        return $this->nextSendDate;
    }

    /**
     * @param \DateTime $nextSendDate
     *
     * @return $this
     */
    public function setNextSendDate(\DateTime $nextSendDate)
    {
        $this->setModelField('nextSendDate', $nextSendDate);

        return $this;
    }

    /**
     * @return array
     */
    public function getSendTo()
    {
        return $this->sendTo;
    }

    /**
     * @param array $sendTo
     *
     * @return $this
     */
    public function setSendTo(array $sendTo)
    {
        $this->setModelField('sendTo', $sendTo);

        return $this;
    }
}

namespace DeskPRO\Bundle\AppBundle\ApiTag\Model;

use JMS\Serializer\Annotation as JMS;

/**
 * Class Tag.
 */
class Tag
{
    /**
     * Autogenerated tag id. Runtime generated.
     *
     * @JMS\Type("integer")
     *
     * @var int
     */
    private $id;

    /**
     * Just a title for the tag.
     *
     * @JMS\Type("string")
     *
     * @var string
     */
    private $title;

    /**
     * Tag permission. 1 - granted. -1 - strictly denied. 0 - soft denied.
     *
     * @JMS\Type("integer")
     *
     * @var int
     */
    private $value;

    /**
     * Children.
     *
     * @JMS\Type("array<DeskPRO\Bundle\AppBundle\ApiTag\Model\Tag>")
     *
     * @var Tag[]|null
     */
    private $nodes;

    /**
     * It`s parent.
     *
     * @JMS\Exclude()
     *
     * @var Tag
     */
    private $parent;

    /**
     * Tag constructor.
     *
     * @param int    $id
     * @param string $title
     */
    public function __construct($id, $title)
    {
        $this->id    = $id;
        $this->title = $title;
    }

    /**
     * @return int
     */
    public function getId()
    {
        return $this->id;
    }

    /**
     * @return Tag[]
     */
    public function getNodes()
    {
        return $this->nodes ?: [];
    }

    /**
     * @param Tag[] $nodes
     *
     * @return $this
     */
    public function setNodes($nodes)
    {
        foreach ($nodes as $node) {
            $node->setParent($this);
            $this->nodes[$node->getId()] = $node;
        }

        return $this;
    }

    /**
     * @param Tag[] $nodes
     */
    public function replaceNodes($nodes)
    {
        $this->nodes = $nodes;
    }

    /**
     * @return bool
     */
    public function hasNodes()
    {
        return $this->nodes && count($this->nodes) > 0;
    }

    /**
     * @return Tag
     */
    public function getParent()
    {
        return $this->parent;
    }

    /**
     * @return bool
     */
    public function hasParent()
    {
        return !is_null($this->parent);
    }

    /**
     * @param Tag $parent
     *
     * @return $this
     */
    public function setParent(Tag $parent)
    {
        $this->parent = $parent;

        return $this;
    }

    /**
     * @return int
     */
    public function getValue()
    {
        return $this->value;
    }

    /**
     * @param int $value
     *
     * @return $this
     */
    public function setValue($value)
    {
        $this->value = $value;

        return $this;
    }

    /**
     * @return string
     */
    public function getTitle()
    {
        return $this->title;
    }

    /**
     * @JMS\VirtualProperty()
     * @JMS\Type("string")
     *
     * @return string
     */
    public function getPath()
    {
        $parts  = [];
        $parent = $this;
        do {
            $parts[] = $parent->getTitle();
        } while ($parent = $parent->getParent());

        $path = implode('.', array_reverse($parts));

        return $path;
    }
}

namespace DeskPRO\Bundle\ApiBundle\View\Representation;

use JMS\Serializer\Annotation as Serializer;

/**
 * @Serializer\ExclusionPolicy("ALL")
 */
class ErrorRepresentation
{
    /**
     * @Serializer\Expose()
     * @Serializer\Type("integer")
     */
    private $status;

    /**
     * @Serializer\Expose()
     * @Serializer\Type("string")
     */
    private $code;

    /**
     * @Serializer\Expose()
     * @Serializer\Type("string")
     */
    private $message;

    /**
     * @Serializer\Expose()
     * @Serializer\Type("array")
     */
    private $errors;

    public function __construct($status, $code, $message, array $errors = null)
    {
        $this->status = $status;
        $this->code = $code;
        $this->message = $message;
        if (!count($errors)) {
            $errors = null;
        }
        $this->errors = $errors;
    }

    /**
     * @return mixed
     */
    public function getStatus()
    {
        return $this->status;
    }

    /**
     * @param mixed $status
     */
    public function setStatus($status)
    {
        $this->status = $status;
    }

    /**
     * @return mixed
     */
    public function getCode()
    {
        return $this->code;
    }

    /**
     * @param mixed $code
     */
    public function setCode($code)
    {
        $this->code = $code;
    }

    /**
     * @return mixed
     */
    public function getMessage()
    {
        return $this->message;
    }

    /**
     * @param mixed $message
     */
    public function setMessage($message)
    {
        $this->message = $message;
    }

    /**
     * @return array
     */
    public function getErrors()
    {
        return $this->errors;
    }

    /**
     * @param array $errors
     */
    public function setErrors(array $errors)
    {
        $this->errors = $errors;
    }
}

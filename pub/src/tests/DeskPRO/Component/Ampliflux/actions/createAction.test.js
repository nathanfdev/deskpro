jest.dontMock('DeskPRO/Component/Ampliflux/actions/createAction');
jest.dontMock('DeskPRO/Component/Ampliflux/actions/actionUtils');

describe('Ampliflux createAction()', () => {
  const { createAction } = require('DeskPRO/Component/Ampliflux/actions/createAction');
  const { isDSA } = require('DeskPRO/Component/Ampliflux/actions/actionUtils');

  it('should produce DeskPRO Standard Actions (DSA)', () => {
    const actionFn = createAction('ID', () => 'payload', () => 'meta');
    const actionObj = actionFn();
    expect(isDSA(actionObj)).toBeTruthy();
  });

  it('should add the passed ID as .type property on action function', () => {
    const action = createAction('TEST_ACTION');
    expect(action).toEqual(jasmine.any(Function));
    expect(action.type).toEqual('TEST_ACTION');
  });

  it('should add the passed ID as .type property to action objects, created by action functions', () => {
    const action = createAction('TEST_ACTION');
    const actionObj = action();
    expect(actionObj.type).toEqual('TEST_ACTION');
  });

  describe('Pass-through actions', () => {
    it('should use the first action fn argument as action payload, when action fn was created with only ID ' +
       'e.g. createAction(\'TEST_ACTION\')',
    () => {
      const action = createAction('TEST_ACTION');
      const testPayload = {one: 1, two: 'two'};
      expect(action(testPayload).payload).toBe(testPayload);
    });

    it('should use the second createAction() argument as action payload when the value is not a function', () => {
      const action = createAction('TEST_ACTION', 'const_payload');
      expect(action().payload).toEqual('const_payload');
    });
  });

  describe('The second actionCreate() function argument', () => {
    it('should be called to generate action object payload', () => {
      const action = createAction('DUMMY_ACTION', () => 'Hello, world!');
      expect(action().payload).toEqual('Hello, world!');
    });

    it('should receive arguments from action fn call', () => {
      const action = createAction('DUMMY_ACTION', (greeting, subject) => `${greeting}, ${subject}!`);
      expect(action('Hello', 'world').payload).toEqual('Hello, world!');
    });
  });

  describe('Action object .meta property', () => {
    it('should be generated by the third createAction() function argument receiving the action object', () => {
      const metaFn = (action) => ({payloadCopy: action.payload, test: 'test'});
      const action = createAction('DUMMY_ACTION', undefined, metaFn);
      const actionObj = action('test payload');
      expect(actionObj.meta).toEqual({payloadCopy: 'test payload', test: 'test'});
    });
  });
});
